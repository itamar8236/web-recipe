// A clock time in the user's own timezone, or '' when it isn't known yet.
export function formatTime(t, ms) {
  if (!ms) return '';
  return new Date(ms).toLocaleTimeString(t.locale, { hour: '2-digit', minute: '2-digit' });
}

// Maps a backend error code to a message in the current language. `nameRequired` is the
// message for a missing name, which depends on what is being named. `error.retryAt` is
// when a quota failure can be tried again.
export function errorMessage(t, error, nameRequired = t.nameRequired) {
  const byCode = {
    invalid_credentials: t.errInvalidCredentials,
    username_taken: t.errUsernameTaken,
    username_invalid: t.errUsernameInvalid,
    password_invalid: t.errPasswordInvalid,
    user_limit: t.errUserLimit,
    network: t.errNetwork,
    name_required: nameRequired,
    too_long: t.errTooLong,
    folder_not_found: t.errFolderNotFound,
    folder_not_empty: t.folderNotEmpty,
    not_found: t.errNotFound,
    link_invalid: t.errLinkInvalid,
    link_unsupported: t.errLinkUnsupported,
    already_imported: t.errAlreadyImported,
    too_many_imports: t.errTooManyImports,
    video_unavailable: t.errVideoUnavailable,
    video_private: t.errVideoPrivate,
    video_too_long: t.errVideoTooLong,
    no_recipe: t.errNoRecipe,
    multiple_recipes: t.errMultipleRecipes,
    llm_error: t.errTemporary,
    bad_result: t.errBadResult,
    model_approval_needed: t.errApprovalNeeded,
    quota: t.errQuota(formatTime(t, error?.retryAt)),
    timed_out: t.errTimedOut,
    not_retryable: t.errNotRetryable,
    not_rerunnable: t.errNotRerunnable,
    best_model_unavailable: t.errBestUnavailable,
    import_needs_login: t.errImportNeedsLogin,
  };
  return byCode[error?.code] ?? t.errGeneric;
}

export const languageLabels = { en: 'English', he: 'עברית' };

// Recipes hold both languages. Show the current one, or fall back to the other
// language when it hasn't been written yet.
export function pickLanguage(recipe, lang) {
  if (recipe[lang].name) return { ...recipe[lang], translated: true };
  const other = lang === 'en' ? 'he' : 'en';
  return { ...recipe[other], translated: false };
}
